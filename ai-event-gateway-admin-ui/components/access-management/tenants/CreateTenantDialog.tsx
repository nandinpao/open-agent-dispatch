'use client';

import { useState, type FormEvent } from 'react';
import { useAccessManagement } from '../AccessManagementProvider';
import { accessManagementApi } from '@/lib/api/accessManagementApi';
import { formatIamError } from '@/lib/iam/errorPresentation';
import type { Tenant } from '@/lib/iam/types';
import { AuditReasonSelector, FieldLabel, SelectField, isAuditReasonValid } from '../shared/beginnerUi';
import { WorkspaceError, WorkspaceModal } from '../shared/workspaceUi';

const TIMEZONES = [
  { value: 'Asia/Taipei', label: 'Taipei (UTC+8)' },
  { value: 'Asia/Ho_Chi_Minh', label: 'Ho Chi Minh City (UTC+7)' },
  { value: 'Asia/Shanghai', label: 'Shanghai (UTC+8)' },
  { value: 'Asia/Tokyo', label: 'Tokyo (UTC+9)' },
  { value: 'UTC', label: 'UTC' },
];
const LOCALES = [
  { value: 'en-US', label: 'English (United States)' },
  { value: 'zh-TW', label: 'Traditional Chinese' },
  { value: 'zh-CN', label: 'Simplified Chinese' },
  { value: 'vi-VN', label: 'Vietnamese' },
  { value: 'ja-JP', label: 'Japanese' },
];
const REGIONS = [
  { value: 'TW', label: 'Taiwan' },
  { value: 'VN', label: 'Vietnam' },
  { value: 'CN', label: 'China' },
  { value: 'JP', label: 'Japan' },
  { value: 'GLOBAL', label: 'Global' },
];

export function CreateTenantDialog({ open, onClose, onCreated }: Readonly<{ open: boolean; onClose: () => void; onCreated?: (tenant: Tenant) => void }>) {
  const { refreshTenants, setScopeTenantId } = useAccessManagement();
  const [timezone, setTimezone] = useState('Asia/Taipei');
  const [locale, setLocale] = useState('en-US');
  const [dataRegion, setDataRegion] = useState('TW');
  const [auditReason, setAuditReason] = useState('New Tenant setup');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const form = event.currentTarget;
    const data = new FormData(form);
    setBusy(true); setError('');
    try {
      const created = await accessManagementApi.createTenant({
        tenantId: null,
        tenantCode: String(data.get('tenantCode') ?? '').trim(),
        tenantName: String(data.get('tenantName') ?? '').trim(),
        legalName: String(data.get('legalName') ?? '').trim(),
        timezone,
        locale,
        dataRegion,
      }, auditReason);
      await refreshTenants();
      onCreated?.(created);
      onClose();
      await setScopeTenantId(created.tenantId);
    } catch (cause) {
      setError(formatIamError(cause, 'Tenant creation failed.'));
    } finally {
      setBusy(false);
    }
  }

  return (
    <WorkspaceModal open={open} onClose={onClose} title="Create Tenant" description="Create the company or business-unit boundary. The internal Tenant ID is generated by the server.">
      <form onSubmit={submit} className="space-y-5">
        {error ? <WorkspaceError title="Tenant creation failed" message={error} /> : null}
        <div className="grid gap-4 sm:grid-cols-2">
          <FieldLabel htmlFor="tenant-tenant-code" label="Tenant code" help="A short business code used in lists and reports." required>
            <input id="tenant-tenant-code" name="tenantCode" required maxLength={32} placeholder="VN01" className="w-full rounded-xl border border-slate-300 px-3 py-2.5 text-sm outline-none focus:border-blue-600 focus:ring-2 focus:ring-blue-100" />
          </FieldLabel>
          <FieldLabel htmlFor="tenant-tenant-name" label="Tenant name" help="The name administrators will see." required>
            <input id="tenant-tenant-name" name="tenantName" required maxLength={120} placeholder="Vietnam Company" className="w-full rounded-xl border border-slate-300 px-3 py-2.5 text-sm outline-none focus:border-blue-600 focus:ring-2 focus:ring-blue-100" />
          </FieldLabel>
          <div className="sm:col-span-2"><FieldLabel htmlFor="tenant-tenant-legal-name" label="Legal name" help="Optional registered legal entity name."><input id="tenant-tenant-legal-name" name="legalName" maxLength={180} placeholder="Registered legal entity name" className="w-full rounded-xl border border-slate-300 px-3 py-2.5 text-sm outline-none focus:border-blue-600 focus:ring-2 focus:ring-blue-100" /></FieldLabel></div>
          <FieldLabel htmlFor="tenant-tenant-timezone" label="Time zone" required><SelectField id="tenant-tenant-timezone" value={timezone} onChange={setTimezone} options={TIMEZONES} required /></FieldLabel>
          <FieldLabel htmlFor="tenant-tenant-locale" label="Default language" required><SelectField id="tenant-tenant-locale" value={locale} onChange={setLocale} options={LOCALES} required /></FieldLabel>
          <div className="sm:col-span-2"><FieldLabel htmlFor="tenant-tenant-region" label="Data region" required><SelectField id="tenant-tenant-region" value={dataRegion} onChange={setDataRegion} options={REGIONS} required /></FieldLabel></div>
        </div>
        <AuditReasonSelector idPrefix="tenant-create-tenant" value={auditReason} onChange={setAuditReason} />
        <div className="flex flex-wrap justify-end gap-2 border-t border-slate-200 pt-4">
          <button type="button" onClick={onClose} disabled={busy} className="rounded-xl border border-slate-300 px-4 py-2.5 text-sm font-black text-slate-700">Cancel</button>
          <button disabled={busy || !isAuditReasonValid(auditReason, 'ROUTINE')} className="rounded-xl bg-blue-700 px-5 py-2.5 text-sm font-black text-white disabled:opacity-50">{busy ? 'Creating…' : 'Create and open workspace'}</button>
        </div>
      </form>
    </WorkspaceModal>
  );
}
